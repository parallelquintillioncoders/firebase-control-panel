'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const os=require('node:os');
const express=require('express');
const {chromium}=require('playwright');

(async()=>{
  const app=express();
  app.use(express.static(path.join(__dirname,'../public')));
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});
  let browser;
  try {
    browser=await chromium.launch({channel:'chrome',headless:true});
    const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    const errors=[], writes=[];
    let refreshes=0,signedIn=true,logoutFails=false;
    page.on('pageerror',error=>errors.push(error.message));
    page.on('dialog',dialog=>dialog.dismiss());
    await page.addInitScript(()=>{if(window===top)localStorage.setItem('pqc.launchpad.consent.v1','declined');});
    await page.route('**/api/**',route=>{
      const req=route.request(),url=new URL(req.url());
      if(req.method()!=='GET')writes.push(url.pathname);
      if(url.pathname==='/api/logout') {
        if(logoutFails)return route.fulfill({status:500,json:{error:'Test logout failure'}});
        signedIn=false;
        return route.fulfill({json:{ok:true}});
      }
      let data={};
      if(url.pathname==='/api/boot')data={requiresAuth:false,authenticated:true};
      if(url.pathname==='/api/health')data={cli:'ready',version:'15.0'};
      if(url.pathname==='/api/auth/status')data={signedIn,accounts:signedIn?['demo@example.test']:[]};
      if(url.pathname==='/api/auth/connect')data={opened:true,message:'Mock sign-in window opened.'};
      if(url.pathname==='/api/projects'){refreshes++;data={projects:[{id:'demo-project',name:'Overview'}]};}
      if(url.pathname==='/api/sites')data={sites:[{id:'demo-site',name:'Overview',url:'https://demo-site.web.app'}]};
      if(url.pathname==='/api/staged')data={builds:[]};
      if(url.pathname==='/api/jobs')data={jobs:[]};
      return route.fulfill({json:data});
    });
    const base=`http://127.0.0.1:${server.address().port}`;
    await page.goto(base);
    await page.waitForFunction(()=>!window.LaunchpadBridge.state.loading);
    assert.equal(await page.locator('html').getAttribute('data-theme'),'flame');
    assert.equal(await page.locator('html').getAttribute('data-mode'),'light');
    assert.equal(await page.locator('.brand-logo').getAttribute('src'),'/flame-logo.png?v=1');
    await page.locator('#accountMenuButton').click();
    assert.equal(await page.locator('#accountPanelEmail').textContent(),'demo@example.test');
    await page.screenshot({path:path.join(os.tmpdir(),'pqc-account-menu-desktop.png')});
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#accountPanel').isVisible(),false);
    await page.locator('#accountMenuButton').click();
    await page.locator('#accountPanel [data-go="settings"]').click();
    assert.equal(await page.locator('#view-settings').isVisible(),true);
    assert.equal(await page.locator('#accountPanel').isVisible(),false);
    await page.locator('.breadcrumb-home').click();
    assert.equal(await page.locator('#view-overview').isVisible(),true);
    const count=refreshes;
    await Promise.all([page.waitForResponse(r=>new URL(r.url()).pathname==='/api/projects'),page.locator('#refreshBtn').click()]);
    assert.ok(refreshes>count);
    await page.locator('#logoutBtn').click();
    assert.deepEqual(writes,[],'Cancelled logout must not mutate account');
    await page.screenshot({path:path.join(os.tmpdir(),'pqc-flame-light.png'),fullPage:true});
    await page.locator('.topbar [data-mode-toggle]').click();
    assert.equal(await page.locator('html').getAttribute('data-mode'),'dark');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('data-mode'),'dark');
    await page.waitForFunction(()=>!window.LaunchpadBridge.state.loading);
    await page.screenshot({path:path.join(os.tmpdir(),'pqc-flame-dark.png'),fullPage:true});
    await page.locator('.topbar-actions [data-preference="theme"]').selectOption('classic');
    await page.reload();
    assert.equal(await page.locator('html').getAttribute('data-theme'),'classic');
    await page.locator('.topbar [data-mode-toggle]').click();
    const color=await page.locator('#headerUpload').evaluate(el=>getComputedStyle(el).backgroundColor);
    assert.equal(color,'rgb(85, 92, 222)','Original purple primary restored');
    for(const [language,overview] of [['es','Resumen'],['ru','Обзор'],['fr','Vue d’ensemble'],['de','Übersicht'],['pt','Visão geral'],['ar','نظرة عامة'],['zh','概览'],['en','Overview']]) {
      await page.locator('.topbar-actions [data-preference="language"]').selectOption(language);
      await page.waitForFunction(expected=>document.querySelector('.nav-item[data-view="overview"] span').textContent===expected,overview);
      assert.equal(await page.locator('html').getAttribute('lang'),language);
      assert.equal(await page.locator('html').getAttribute('dir'),language==='ar'?'rtl':'ltr');
      assert.equal(await page.locator('#featuredSites .site-card-name').first().textContent(),'Overview','User site name must remain original');
      await page.locator('[data-view="settings"]').click();
      await page.locator('[data-view="overview"]').click();
      await page.waitForFunction(expected=>document.getElementById('breadcrumb').textContent===expected,overview);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`No overflow in ${language}`);
    }
    await page.locator('.topbar-actions [data-preference="language"]').selectOption('es');
    await page.reload();
    await page.waitForFunction(()=>document.getElementById('breadcrumb').textContent==='Resumen');
    await page.locator('.topbar-actions [data-preference="theme"]').selectOption('flame');
    await page.locator('#easyLaunchTop').click();
    await page.locator('#easyPage [data-mode-toggle]').click();
    assert.equal(await page.locator('html').getAttribute('data-mode'),'dark');
    await page.screenshot({path:path.join(os.tmpdir(),'pqc-wizard-dark-es.png')});
    await page.locator('#ezClose').click();
    await page.setViewportSize({width:375,height:812});
    await page.locator('.topbar-actions [data-preference="language"]').selectOption('ar');
    await page.locator('#mobileMenu').click();
    await page.locator('[data-view="settings"]').click();
    assert.equal(await page.locator('#sidebarBackdrop').isVisible(),false);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No RTL mobile overflow');
    await page.evaluate(()=>window.scrollTo(0,0));
    await page.screenshot({path:path.join(os.tmpdir(),'pqc-mobile-dark-ar.png'),fullPage:true});
    await page.locator('#accountMenuButton').click();
    assert.ok(await page.locator('#accountPanel').isVisible());
    await page.keyboard.press('Escape');
    await page.locator('.topbar-actions [data-preference="language"]').selectOption('en');
    await page.locator('.topbar-actions [data-preference="theme"]').selectOption('classic');
    await page.locator('.topbar [data-mode-toggle]').click();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No classic mobile overflow');
    await page.locator('#accountMenuButton').click();
    await page.locator('#accountPanel [data-preference="theme"]').selectOption('flame');
    await page.locator('#accountPanel [data-preference="mode"]').selectOption('dark');
    await page.locator('#accountPanel [data-preference="language"]').selectOption('es');
    assert.equal(await page.locator('.topbar-actions [data-preference="theme"]').inputValue(),'flame');
    assert.equal(await page.locator('.topbar-actions [data-preference="language"]').inputValue(),'es');
    assert.equal(await page.locator('html').getAttribute('data-mode'),'dark');
    assert.equal(await page.locator('#accountLogin').isVisible(),false);
    assert.equal(await page.locator('#accountLogout').isVisible(),true);
    const menuBox=await page.locator('#accountPanel').boundingBox();
    assert.ok(menuBox.x>=0&&menuBox.x+menuBox.width<=375&&menuBox.y+menuBox.height<=812,'Menu fits mobile viewport');
    await page.screenshot({path:path.join(os.tmpdir(),'pqc-account-menu-mobile.png'),fullPage:true});
    await page.locator('#accountClose').click();
    assert.equal(await page.locator('#accountMenuButton').evaluate(el=>el===document.activeElement),true);
    await page.locator('#accountMenuButton').click();
    await page.locator('#accountCookies').click();
    assert.equal(await page.locator('#cookieBanner').isVisible(),true);
    await page.locator('#cookieDecline').click();
    await page.locator('#accountMenuButton').click();
    await page.locator('#accountPanel [data-preference="language"]').selectOption('en');
    await page.locator('#accountLogout').click();
    assert.deepEqual(writes,[],'Cancelled menu logout must not mutate account');
    page.removeAllListeners('dialog');
    page.on('dialog',dialog=>dialog.accept());
    logoutFails=true;
    await page.locator('#accountLogout').click();
    await page.waitForFunction(()=>!document.getElementById('accountLogout').disabled);
    assert.equal(await page.locator('#accountLogout').isVisible(),true);
    logoutFails=false;
    await page.locator('#accountLogout').click();
    await page.waitForFunction(()=>window.LaunchpadBridge?.state.authStatus?.signedIn===false);
    assert.equal(await page.locator('#logoutBtn').isVisible(),false);
    assert.equal(await page.locator('#accountLoginTop').isVisible(),true);
    await page.locator('#accountMenuButton').click();
    assert.equal(await page.locator('#accountLogout').isVisible(),false);
    await page.locator('#accountLogin').click();
    await page.waitForFunction(()=>document.getElementById('connectInfo').textContent.includes('Mock sign-in'));
    assert.ok(writes.includes('/api/auth/connect'),'Menu login starts existing login flow');
    assert.equal(await page.locator('#view-settings').isVisible(),true);
    // Simulate completed browser authorization and refresh the account display.
    signedIn=true;
    await page.locator('#checkLogin').click();
    await page.waitForFunction(()=>window.LaunchpadBridge.state.authStatus?.signedIn===true);
    assert.equal(await page.locator('#logoutBtn').isVisible(),true);
    assert.equal(await page.locator('#accountLoginTop').isVisible(),false);
    const fallback=await browser.newPage();
    fallback.on('pageerror',error=>errors.push(error.message));
    await fallback.route('**/api/**',route=>route.fulfill({json:{requiresAuth:false,authenticated:true,projects:[],sites:[],jobs:[],builds:[],signedIn:false,accounts:[]}}));
    await fallback.addInitScript(()=>{
      Storage.prototype.getItem=function(){throw new DOMException('Unavailable','SecurityError');};
      Storage.prototype.setItem=function(){throw new DOMException('Unavailable','SecurityError');};
    });
    await fallback.goto(base);
    assert.equal(await fallback.locator('html').getAttribute('data-theme'),'flame');
    await fallback.locator('.topbar [data-mode-toggle]').click();
    assert.equal(await fallback.locator('html').getAttribute('data-mode'),'dark');
    await fallback.locator('.topbar-actions [data-preference="language"]').selectOption('ru');
    await fallback.waitForFunction(()=>document.getElementById('breadcrumb').textContent==='Обзор');
    await fallback.close();
    assert.deepEqual(errors,[]);
    console.log('PASS: themes, light/dark persistence, eight languages, navigation, RTL/mobile, unavailable storage, account preferences, settings, cookies, login, failed/cancelled/successful logout and refreshed account state. Mock API only.');
  } finally {
    await browser?.close();
    await new Promise(resolve=>server.close(resolve));
  }
})().catch(error=>{console.error(error);process.exitCode=1;});
